//! Aether GPU Compute Backend
//! Lowers `kernel` declarations to GPU compute shaders (WGSL/SPIR-V)
//! with thread-index mapping and explicit buffer transfers.

const std = @import("std");
const parser = @import("parser.zig");
const Node = parser.Node;

pub const ExecutionTier = enum {
    inline_cpu,
    parallel_cpu_pool,
    gpu_device,
};

pub const KernelScheduler = struct {
    pub fn selectTier(element_count: usize, ops_per_elem: usize, gpu_available: bool) ExecutionTier {
        const total_ops = element_count * ops_per_elem;
        if (total_ops < 4096) {
            return .inline_cpu;
        } else if (gpu_available and total_ops >= 262144) {
            return .gpu_device;
        } else {
            return .parallel_cpu_pool;
        }
    }
};

pub const GpuDriverRuntime = struct {
    cu_handle: ?*anyopaque = null,
    cu_init_fn: ?*const fn (u32) callconv(.c) i32 = null,
    cu_device_count_fn: ?*const fn (*i32) callconv(.c) i32 = null,
    initialized: bool = false,
    device_count: i32 = 0,

    pub fn init() GpuDriverRuntime {
        var rt = GpuDriverRuntime{};
        if (@import("builtin").os.tag == .windows) {
            const kernel32_dll = struct {
                extern "kernel32" fn LoadLibraryA([*:0]const u8) callconv(.c) ?*anyopaque;
                extern "kernel32" fn GetProcAddress(?*anyopaque, [*:0]const u8) callconv(.c) ?*const anyopaque;
            };
            if (kernel32_dll.LoadLibraryA("nvcuda.dll")) |h| {
                rt.cu_handle = h;
                if (kernel32_dll.GetProcAddress(h, "cuInit")) |p| {
                    rt.cu_init_fn = @ptrCast(p);
                    if (rt.cu_init_fn.?(0) == 0) {
                        rt.initialized = true;
                        if (kernel32_dll.GetProcAddress(h, "cuDeviceGetCount")) |p2| {
                            rt.cu_device_count_fn = @ptrCast(p2);
                            var cnt: i32 = 0;
                            if (rt.cu_device_count_fn.?(&cnt) == 0) {
                                rt.device_count = cnt;
                            }
                        }
                    }
                }
            }
        }
        return rt;
    }

    pub fn isAvailable(self: *const GpuDriverRuntime) bool {
        return self.initialized and self.device_count > 0;
    }
};

pub const GPUBackend = struct {
    allocator: std.mem.Allocator,

    pub fn init(allocator: std.mem.Allocator) GPUBackend {
        return .{ .allocator = allocator };
    }

    /// Lowers an Aether kernel into a WGSL / WebGPU compute shader
    pub fn lowerToWGSL(self: *GPUBackend, kernel_node: *Node) ![]const u8 {
        if (kernel_node.data != .list or kernel_node.data.list.len < 4) return error.InvalidKernelSyntax;
        const children = kernel_node.data.list;
        const name = children[1].data.atom.symbol;

        const params_node = children[2];
        const params = if (params_node.data == .list) params_node.data.list else params_node.data.bracket_list;

        var out: std.ArrayList(u8) = .empty;

        try out.appendSlice(self.allocator, "// WebGPU Compute Shader generated by Aether\n");

        var param_names: std.ArrayList([]const u8) = .empty;
        for (params) |p| {
            if (p.data == .list and p.data.list.len >= 1 and p.data.list[0].data == .atom and p.data.list[0].data.atom == .symbol) {
                try param_names.append(self.allocator, p.data.list[0].data.atom.symbol);
            } else if (p.data == .atom and p.data.atom == .symbol) {
                try param_names.append(self.allocator, p.data.atom.symbol);
            }
        }

        // Determine which buffers are outputs (written to via set)
        var write_buffers = std.StringHashMap(void).init(self.allocator);
        for (children[3..]) |stmt| {
            if (stmt.data == .list and stmt.data.list.len >= 2 and stmt.data.list[0].data == .atom and std.mem.eql(u8, stmt.data.list[0].data.atom.symbol, "set")) {
                const target_buf = stmt.data.list[1].data.atom.symbol;
                try write_buffers.put(target_buf, {});
            }
        }

        // Emit storage buffers
        for (param_names.items, 0..) |pname, idx| {
            const is_write = write_buffers.contains(pname) or idx == param_names.items.len - 1;
            const mode = if (is_write) "read_write" else "read";
            var buf: [128]u8 = undefined;
            const line = try std.fmt.bufPrint(&buf, "@group(0) @binding({d}) var<storage, {s}> {s}: array<f32>;\n", .{ idx, mode, pname });
            try out.appendSlice(self.allocator, line);
        }
        try out.appendSlice(self.allocator, "\n@compute @workgroup_size(64)\n");
        try out.appendSlice(self.allocator, "fn ");
        try out.appendSlice(self.allocator, name);
        try out.appendSlice(self.allocator, "(@builtin(global_invocation_id) global_id: vec3<u32>) {\n");
        try out.appendSlice(self.allocator, "    let idx: u32 = global_id.x;\n");
        if (param_names.items.len > 0) {
            var b_buf: [128]u8 = undefined;
            const bound_check = try std.fmt.bufPrint(&b_buf, "    if (idx >= arrayLength(&{s})) {{ return; }}\n", .{param_names.items[0]});
            try out.appendSlice(self.allocator, bound_check);
        }

        // Lower body statements
        for (children[3..]) |stmt| {
            if (stmt.data != .list or stmt.data.list.len == 0) continue;
            const s_head = stmt.data.list[0];
            if (s_head.data != .atom or s_head.data.atom != .symbol) continue;
            const op = s_head.data.atom.symbol;

            if (std.mem.eql(u8, op, "let")) {
                // (let idx global_id) is handled by built-in global_id.x
                continue;
            } else if (std.mem.eql(u8, op, "set")) {
                // (set target idx expr)
                if (stmt.data.list.len >= 4) {
                    const target = stmt.data.list[1].data.atom.symbol;
                    const idx_expr = stmt.data.list[2];
                    const val_expr = stmt.data.list[3];

                    try out.appendSlice(self.allocator, "    ");
                    try out.appendSlice(self.allocator, target);
                    try out.appendSlice(self.allocator, "[");
                    try self.lowerExprToWGSL(&out, idx_expr);
                    try out.appendSlice(self.allocator, "] = ");
                    try self.lowerExprToWGSL(&out, val_expr);
                    try out.appendSlice(self.allocator, ";\n");
                }
            }
        }

        try out.appendSlice(self.allocator, "}\n");
        return try out.toOwnedSlice(self.allocator);
    }

