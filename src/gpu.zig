    /// Lowers an Aether kernel into a Vulkan SPIR-V compute shader (GLSL)
    pub fn lowerToSPIRV(self: *GPUBackend, kernel_node: *Node) ![]const u8 {
        if (kernel_node.data != .list or kernel_node.data.list.len < 4) return error.InvalidKernelSyntax;
        const children = kernel_node.data.list;

        const params_node = children[2];
        const params = if (params_node.data == .list) params_node.data.list else params_node.data.bracket_list;

        var out: std.ArrayList(u8) = .empty;
        try out.appendSlice(self.allocator, "// Vulkan Compute Shader (SPIR-V source) generated by Aether\n");
        try out.appendSlice(self.allocator, "#version 450\n");
        try out.appendSlice(self.allocator, "layout(local_size_x = 64, local_size_y = 1, local_size_z = 1) in;\n\n");

        var param_names: std.ArrayList([]const u8) = .empty;
        for (params) |p| {
            if (p.data == .list and p.data.list.len >= 1 and p.data.list[0].data == .atom and p.data.list[0].data.atom == .symbol) {
                try param_names.append(self.allocator, p.data.list[0].data.atom.symbol);
            } else if (p.data == .atom and p.data.atom == .symbol) {
                try param_names.append(self.allocator, p.data.atom.symbol);
            }
        }

        var write_buffers = std.StringHashMap(void).init(self.allocator);
        for (children[3..]) |stmt| {
            if (stmt.data == .list and stmt.data.list.len >= 2 and stmt.data.list[0].data == .atom and std.mem.eql(u8, stmt.data.list[0].data.atom.symbol, "set")) {
                const target_buf = stmt.data.list[1].data.atom.symbol;
                try write_buffers.put(target_buf, {});
            }
        }

        for (param_names.items, 0..) |pname, idx| {
            const is_write = write_buffers.contains(pname) or idx == param_names.items.len - 1;
            var b_buf: [256]u8 = undefined;
            const line = if (is_write)
                try std.fmt.bufPrint(&b_buf, "layout(std430, binding = {d}) buffer Buf_{s} {{ float {s}[]; }};\n", .{ idx, pname, pname })
            else
                try std.fmt.bufPrint(&b_buf, "layout(std430, binding = {d}) readonly buffer Buf_{s} {{ float {s}[]; }};\n", .{ idx, pname, pname });
            try out.appendSlice(self.allocator, line);
        }

        try out.appendSlice(self.allocator, "\nvoid main() {\n");
        try out.appendSlice(self.allocator, "    uint idx = gl_GlobalInvocationID.x;\n");

        for (children[3..]) |stmt| {
            if (stmt.data != .list or stmt.data.list.len == 0) continue;
            const s_head = stmt.data.list[0];
            if (s_head.data != .atom or s_head.data.atom != .symbol) continue;
            const op = s_head.data.atom.symbol;

            if (std.mem.eql(u8, op, "let")) {
                continue;
            } else if (std.mem.eql(u8, op, "set")) {
                if (stmt.data.list.len >= 4) {
                    const target = stmt.data.list[1].data.atom.symbol;
                    const val_expr = stmt.data.list[3];

                    try out.appendSlice(self.allocator, "    ");
                    try out.appendSlice(self.allocator, target);
                    try out.appendSlice(self.allocator, "[idx] = ");
                    try self.lowerExprToWGSL(&out, val_expr);
                    try out.appendSlice(self.allocator, ";\n");
                }
            }
        }

        try out.appendSlice(self.allocator, "}\n");
        return try out.toOwnedSlice(self.allocator);
    }

    fn lowerExprToWGSL(self: *GPUBackend, out: *std.ArrayList(u8), node: *Node) anyerror!void {
        switch (node.data) {
            .atom => |a| switch (a) {
                .number => |n| {
                    var buf: [32]u8 = undefined;
                    const s = if (@floor(n) == n)
                        try std.fmt.bufPrint(&buf, "{d}.0", .{@as(i64, @intFromFloat(n))})
                    else
                        try std.fmt.bufPrint(&buf, "{d}", .{n});
                    try out.appendSlice(self.allocator, s);
                },
                .symbol => |s| try out.appendSlice(self.allocator, s),
                else => try out.appendSlice(self.allocator, "0.0"),
            },
            .bracket_list => {},
            .list => |children| {
                if (children.len == 0) return;
                const head = children[0];
                if (head.data != .atom or head.data.atom != .symbol) return;
                const op = head.data.atom.symbol;

                if (std.mem.eql(u8, op, "index") and children.len >= 3) {
                    const buf_name = children[1].data.atom.symbol;
                    try out.appendSlice(self.allocator, buf_name);
                    try out.appendSlice(self.allocator, "[");
                    try self.lowerExprToWGSL(out, children[2]);
                    try out.appendSlice(self.allocator, "]");
                } else if ((std.mem.eql(u8, op, "+") or std.mem.eql(u8, op, "-") or std.mem.eql(u8, op, "*") or std.mem.eql(u8, op, "/")) and children.len >= 3) {
                    try out.appendSlice(self.allocator, "(");
                    try self.lowerExprToWGSL(out, children[1]);
                    try out.append(self.allocator, ' ');
                    try out.appendSlice(self.allocator, op);
                    try out.append(self.allocator, ' ');
                    try self.lowerExprToWGSL(out, children[2]);
                    try out.appendSlice(self.allocator, ")");
                } else {
                    try self.lowerExprToWGSL(out, children[1]);
                }
            },
        }
    }
};

test "GPU compute shader generation emits valid WGSL kernel" {
    const src =
        \\(kernel vector_double ((in Tensor<f32>) (out Tensor<f32>))
        \\  (let idx global_id)
        \\  (set out idx (* (index in idx) 2.0)))
    ;

    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();

    var p = try parser.Parser.init(src, arena.allocator());
    const nodes = try p.parseAll();
    try std.testing.expectEqual(@as(usize, 1), nodes.len);

    var gpu_backend = GPUBackend.init(arena.allocator());
    const shader = try gpu_backend.lowerToWGSL(nodes[0]);

    try std.testing.expect(std.mem.indexOf(u8, shader, "@compute @workgroup_size(64)") != null);
    try std.testing.expect(std.mem.indexOf(u8, shader, "fn vector_double") != null);
    try std.testing.expect(std.mem.indexOf(u8, shader, "out[idx] = (in[idx] * 2.0);") != null);

    const cuda_src = try gpu_backend.lowerToCUDA(nodes[0]);
    try std.testing.expect(std.mem.indexOf(u8, cuda_src, "__global__ void vector_double") != null);
    try std.testing.expect(std.mem.indexOf(u8, cuda_src, "blockDim.x * blockIdx.x + threadIdx.x") != null);

    const hip_src = try gpu_backend.lowerToHIP(nodes[0]);
    try std.testing.expect(std.mem.indexOf(u8, hip_src, "hipBlockDim_x * hipBlockIdx_x + hipThreadIdx_x") != null);

    const spirv_src = try gpu_backend.lowerToSPIRV(nodes[0]);
    try std.testing.expect(std.mem.indexOf(u8, spirv_src, "layout(local_size_x = 64") != null);
}
