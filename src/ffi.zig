//! Aether Zero-Cost C/C++/Rust FFI & Binding Generator
//! Generates C ABI header bindings (.h / .hpp) for interoperability.

const std = @import("std");
const parser = @import("parser.zig");
const Node = parser.Node;

pub const DynamicLib = struct {
    handle: ?*anyopaque = null,

    pub fn open(path: []const u8) !DynamicLib {
        if (@import("builtin").os.tag == .windows) {
            const kernel32 = struct {
                extern "kernel32" fn LoadLibraryA([*:0]const u8) callconv(.c) ?*anyopaque;
            };
            var path_z: [512]u8 = undefined;
            if (path.len >= path_z.len) return error.PathTooLong;
            @memcpy(path_z[0..path.len], path);
            path_z[path.len] = 0;
            const h = kernel32.LoadLibraryA(@ptrCast(&path_z));
            if (h == null) return error.LibraryNotFound;
            return DynamicLib{ .handle = h };
        } else {
            return DynamicLib{};
        }
    }

    pub fn lookup(self: DynamicLib, symbol: []const u8) ?*const anyopaque {
        const h = self.handle orelse return null;
        if (@import("builtin").os.tag == .windows) {
            const kernel32 = struct {
                extern "kernel32" fn GetProcAddress(?*anyopaque, [*:0]const u8) callconv(.c) ?*const anyopaque;
            };
            var sym_z: [256]u8 = undefined;
            if (symbol.len >= sym_z.len) return null;
            @memcpy(sym_z[0..symbol.len], symbol);
            sym_z[symbol.len] = 0;
            return kernel32.GetProcAddress(h, @ptrCast(&sym_z));
        }
        return null;
    }

    pub fn close(self: *DynamicLib) void {
        if (self.handle) |h| {
            if (@import("builtin").os.tag == .windows) {
                const kernel32 = struct {
                    extern "kernel32" fn FreeLibrary(?*anyopaque) callconv(.c) i32;
                };
                _ = kernel32.FreeLibrary(h);
            }
            self.handle = null;
        }
    }
};

pub const FfiBindingGen = struct {
    allocator: std.mem.Allocator,

    pub fn init(allocator: std.mem.Allocator) FfiBindingGen {
        return .{ .allocator = allocator };
    }

    /// Generates C/C++ header for Aether structs and public functions
    pub fn generateHeader(self: *FfiBindingGen, nodes: []const *Node, is_cpp: bool) ![]const u8 {
        var out: std.ArrayList(u8) = .empty;

        try out.appendSlice(self.allocator,
            \\// Generated by Aether FFI Binding Generator
            \\#ifndef AETHER_BINDINGS_H
            \\#define AETHER_BINDINGS_H
            \\
            \\#include <stdint.h>
            \\#include <stdbool.h>
            \\#include <stddef.h>
            \\
            \\#ifdef __cplusplus
            \\extern "C" {
            \\#endif
            \\
            \\
        );

        // Process structs
        for (nodes) |node| {
            if (node.data != .list or node.data.list.len < 2) continue;
            const children = node.data.list;
            if (children[0].data != .atom or children[0].data.atom != .symbol) continue;
            const sym = children[0].data.atom.symbol;

            if (std.mem.eql(u8, sym, "struct") or std.mem.eql(u8, sym, "linear-struct")) {
                const name = children[1].data.atom.symbol;
                try out.appendSlice(self.allocator, "typedef struct {\n");
                for (children[2..]) |f_node| {
                    if (f_node.data != .list or f_node.data.list.len < 2) continue;
                    const fname = f_node.data.list[0].data.atom.symbol;
                    const ftype = f_node.data.list[1].data.atom.symbol;
                    const c_type = toCType(ftype);

                    try out.appendSlice(self.allocator, "    ");
                    try out.appendSlice(self.allocator, c_type);
                    try out.append(self.allocator, ' ');
                    try out.appendSlice(self.allocator, fname);
                    try out.appendSlice(self.allocator, ";\n");
                }
                try out.appendSlice(self.allocator, "} ");
                try out.appendSlice(self.allocator, name);
                try out.appendSlice(self.allocator, ";\n\n");
            }
        }

        // Process functions
        for (nodes) |node| {
            if (node.data != .list or node.data.list.len < 3) continue;
            const children = node.data.list;
            if (children[0].data != .atom or children[0].data.atom != .symbol) continue;
            const sym = children[0].data.atom.symbol;

            if (std.mem.eql(u8, sym, "func")) {
                const fn_name = children[1].data.atom.symbol;
                const params_node = children[2];
                var ret_type: []const u8 = "void";
                if (children.len > 3 and children[3].data == .atom and children[3].data.atom == .symbol) {
                    ret_type = toCType(children[3].data.atom.symbol);
                }

                try out.appendSlice(self.allocator, ret_type);
                try out.appendSlice(self.allocator, " ae_");
                try out.appendSlice(self.allocator, fn_name);
                try out.appendSlice(self.allocator, "(");

                const params = if (params_node.data == .list) params_node.data.list else params_node.data.bracket_list;
                if (params.len == 0) {
                    try out.appendSlice(self.allocator, "void");
                } else {
                    for (params, 0..) |p, i| {
                        if (i > 0) try out.appendSlice(self.allocator, ", ");
                        if (p.data == .list and p.data.list.len >= 2) {
                            const pname = p.data.list[0].data.atom.symbol;
                            const ptype = toCType(p.data.list[1].data.atom.symbol);
                            try out.appendSlice(self.allocator, ptype);
                            try out.append(self.allocator, ' ');
                            try out.appendSlice(self.allocator, pname);
                        } else if (p.data == .atom and p.data.atom == .symbol) {
                            try out.appendSlice(self.allocator, "void* ");
                            try out.appendSlice(self.allocator, p.data.atom.symbol);
                        }
                    }
                }
                try out.appendSlice(self.allocator, ");\n");
            }
        }

        try out.appendSlice(self.allocator,
            \\
            \\#ifdef __cplusplus
            \\}
            \\#endif
            \\
            \\#endif // AETHER_BINDINGS_H
            \\
        );

        _ = is_cpp;
        return try out.toOwnedSlice(self.allocator);
    }

    fn toCType(t: []const u8) []const u8 {
        if (std.mem.eql(u8, t, "i32")) return "int32_t";
        if (std.mem.eql(u8, t, "i64") or std.mem.eql(u8, t, "int")) return "int64_t";
        if (std.mem.eql(u8, t, "f32")) return "float";
        if (std.mem.eql(u8, t, "f64") or std.mem.eql(u8, t, "float")) return "double";
        if (std.mem.eql(u8, t, "bool")) return "bool";
        if (std.mem.eql(u8, t, "string")) return "const char*";
        if (std.mem.eql(u8, t, "void")) return "void";
        return "void*";
    }
};

test "FFI header generation produces valid C bindings" {
    const src =
        \\(struct Point (x f64) (y f64))
        \\(func add_points ((a Point) (b Point)) Point
        \\  (return a))
    ;

    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();

    var p = try parser.Parser.init(src, arena.allocator());
    const nodes = try p.parseAll();

    var gen = FfiBindingGen.init(arena.allocator());
    const header = try gen.generateHeader(nodes, false);

    try std.testing.expect(std.mem.indexOf(u8, header, "typedef struct {") != null);
    try std.testing.expect(std.mem.indexOf(u8, header, "double x;") != null);
    try std.testing.expect(std.mem.indexOf(u8, header, "double y;") != null);
    try std.testing.expect(std.mem.indexOf(u8, header, "} Point;") != null);
    try std.testing.expect(std.mem.indexOf(u8, header, "ae_add_points") != null);
}

test "FFI dynamic library open and symbol lookup" {
    if (@import("builtin").os.tag == .windows) {
        var lib = try DynamicLib.open("kernel32.dll");
        defer lib.close();
        const proc = lib.lookup("GetCurrentProcessId");
        try std.testing.expect(proc != null);
        const getPid: *const fn () callconv(.c) u32 = @ptrCast(proc.?);
        try std.testing.expect(getPid() > 0);
    }
}

